"use strict";

/**
 * Generates per-account GitHub workflow YAML files from schedule.config.json.
 * Cron defines when to run; the script always posts 1 video (no hour check).
 *
 * Usage: node scripts/generate-workflows.js
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const CONFIG_PATH = path.join(ROOT, "schedule.config.json");
const WORKFLOWS_DIR = path.join(ROOT, ".github", "workflows");

const CRON_WEEKDAY = {
  sunday: 0,
  monday: 1,
  tuesday: 2,
  wednesday: 3,
  thursday: 4,
  friday: 5,
  saturday: 6,
};

const ACCOUNTS = {
  FI: {
    mode: "fi",
    workflowFile: "post-fi.yml",
    title: "Post FI TikToks",
    sheetSecret: "SHEET_ID_FI",
    blotatoSecret: "BLOTATO_ACCOUNT_ID_FI",
  },
  DE: {
    mode: "de",
    workflowFile: "post-de.yml",
    title: "Post DE TikToks",
    sheetSecret: "SHEET_ID_DE",
    blotatoSecret: "BLOTATO_ACCOUNT_ID_DE",
  },
  US: {
    mode: "us",
    workflowFile: "post-us.yml",
    title: "Post US TikToks",
    sheetSecret: "SHEET_ID_US",
    blotatoSecret: "BLOTATO_ACCOUNT_ID_US",
  },
};

function loadConfig() {
  return JSON.parse(fs.readFileSync(CONFIG_PATH, "utf8"));
}

function buildCronLines(config, accountKey) {
  const startHour = config.accounts[accountKey].startHour;
  const timezone = config.timezone || "Europe/Helsinki";
  const lines = [];

  for (const [weekday, count] of Object.entries(config.postsPerWeekday)) {
    if (!count) continue;

    const cronDay = CRON_WEEKDAY[weekday];
    for (let slot = 0; slot < count; slot++) {
      const hour = startHour + slot;
      lines.push(`    - cron: "0 ${hour} * * ${cronDay}"`);
      lines.push(`      timezone: ${timezone}`);
    }
  }

  return lines.join("\n");
}

function buildWorkflowYaml(accountKey, config) {
  const meta = ACCOUNTS[accountKey];
  const cronBlock = buildCronLines(config, accountKey);

  return `# Generated by scripts/generate-workflows.js — do not edit by hand.
# Update schedule.config.json, then run: npm run generate-workflows

name: ${meta.title}

on:
  schedule:
${cronBlock}
  workflow_dispatch:

jobs:
  post:
    name: ${meta.title}
    runs-on: ubuntu-latest

    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

      - name: Set up Node.js 18
        uses: actions/setup-node@v4
        with:
          node-version: 18
          cache: "npm"

      - name: Install dependencies
        run: npm ci

      - name: Run ${accountKey} posting script
        run: node postVideos.js ${meta.mode}
        env:
          CI: "true"
          GOOGLE_CLIENT_EMAIL: \${{ secrets.GOOGLE_CLIENT_EMAIL }}
          GOOGLE_PRIVATE_KEY: \${{ secrets.GOOGLE_PRIVATE_KEY }}
          ${meta.sheetSecret}: \${{ secrets.${meta.sheetSecret} }}
          BLOTATO_API_KEY: \${{ secrets.BLOTATO_API_KEY }}
          ${meta.blotatoSecret}: \${{ secrets.${meta.blotatoSecret} }}
`;
}

function main() {
  const config = loadConfig();

  if (!fs.existsSync(WORKFLOWS_DIR)) {
    fs.mkdirSync(WORKFLOWS_DIR, { recursive: true });
  }

  for (const accountKey of Object.keys(ACCOUNTS)) {
    const yaml = buildWorkflowYaml(accountKey, config);
    const outPath = path.join(WORKFLOWS_DIR, ACCOUNTS[accountKey].workflowFile);
    fs.writeFileSync(outPath, yaml, "utf8");
    console.log(`Wrote ${outPath}`);
  }

  // Remove legacy unified workflow if present
  const legacy = path.join(WORKFLOWS_DIR, "post.yml");
  if (fs.existsSync(legacy)) {
    fs.unlinkSync(legacy);
    console.log(`Removed ${legacy}`);
  }
}

main();
